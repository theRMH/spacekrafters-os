import { supabase } from '../lib/supabase'
import type { LeaveApplication } from '../types'

const TABLE = 'sks_leave_applications'

export async function getAllLeaveApplications(): Promise<LeaveApplication[]> {
  if (!supabase) return []
  const { data, error } = await supabase.from(TABLE).select('data').order('created_at', { ascending: false })
  if (error || !data) return []
  return data.map(r => r.data as LeaveApplication)
}

export async function upsertLeaveApplication(leave: LeaveApplication): Promise<{ ok: boolean; error?: string }> {
  if (!supabase) return { ok: false, error: 'Not configured.' }
  const { error } = await supabase.from(TABLE).upsert({
    id:         leave.id,
    user_id:    leave.userId,
    status:     leave.status,
    data:       leave,
    updated_at: new Date().toISOString(),
  }, { onConflict: 'id' })
  if (error) return { ok: false, error: error.message }
  return { ok: true }
}

export async function deleteLeaveApplication(id: string): Promise<{ ok: boolean; error?: string }> {
  if (!supabase) return { ok: false, error: 'Not configured.' }
  const { error } = await supabase.from(TABLE).delete().eq('id', id)
  if (error) return { ok: false, error: error.message }
  return { ok: true }
}
